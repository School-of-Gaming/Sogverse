/**
 * Fixtures for the admin dashboard preview scene: a plausible autumn term for a
 * platform running sixty products, and the ops queue that comes with it.
 *
 * **Everything here is deterministic.** No `Math.random`, no `Date.now`, no
 * `crypto.randomUUID` at module load or at render — a fixture that changes
 * between two reloads makes a design impossible to compare with itself, and an
 * identicon built from a fresh UUID gives the same person a different face every
 * time the page is opened. The clock is a single pinned instant (below), the
 * product set is generated by index-keyed loops over literal name lists, and
 * every person id is a real UUID pasted in as a literal.
 *
 * **The schedule and the coming-up feed are resolved here, not in the body.** A
 * week's chips are the occurrences that actually fall in it — a term that has
 * not started, one that has ended and a club paused for syysloma all contribute
 * nothing — and the feed's cohorts are already grouped by date and type. That is
 * the same split the live page will want: the aggregation is a query's job, and
 * swapping this module for one is the whole of promotion.
 */

/**
 * **Two scenarios**, and they cannot coexist: a full attention queue and an
 * empty one are the same component in its two states.
 *
 * `busy` is the platform under real load — sixty products, twenty-one of them
 * needing something, five gedus not yet certified. `quiet` is six products with
 * nothing wrong anywhere, which is the only way to see the all-clear header on a
 * page that is otherwise doing its job.
 *
 * **`quiet` still lists gedus, and that is the combination worth having.** The
 * two sections are independent now — attention is products, certification is
 * standing information below it — so the interesting scene is the one that shows
 * a collapsed attention panel *above a populated certification list*: an admin
 * with genuinely nothing to do, looking at people they cannot do anything about
 * yet. Emptying both would have shown two empty states and hidden the pairing
 * the split exists for.
 */
export const ADMIN_DASHBOARD_SCENARIOS = ["busy", "quiet"] as const;

export type AdminDashboardScenario =
  (typeof ADMIN_DASHBOARD_SCENARIOS)[number];

export function isAdminDashboardScenario(
  value: string,
): value is AdminDashboardScenario {
  return (ADMIN_DASHBOARD_SCENARIOS as readonly string[]).includes(value);
}

