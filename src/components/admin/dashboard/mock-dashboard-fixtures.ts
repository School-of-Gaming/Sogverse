/** One product row, in the vocabulary the database actually stores. */
interface ProductSpec {
  id: string;
  name: string;
  productType: ProductType;
  /**
   * Internal to the fixture, and never surfaced to the body: nothing on the
   * dashboard displays a product's status any more. It survives here because
   * resolution needs it — a cancelled or completed run has no occurrences
   * whatever its slots still say, and a completed camp sitting in last week's
   * rows would be a lie the schedule told about itself.
   */
  status: ProductStatus;
  startDate: string;
  endDate: string | null;
  /** `null` is uncapped — not "no seats". */
  seatCount: number | null;
  activeCount: number;
  slots: readonly {
    /** 0 = Monday … 6 = Sunday. */
    weekday: number;
    startTime: string;
    durationMinutes: number;
  }[];
  /**
   * Mondays this product does not run, as bare calendar dates.
   *
   * Modelled because a resolved week has to be able to say "absent on purpose".
   * A school club is closed for syysloma, and a week where four of them vanish
   * with no explanation is indistinguishable from a week where four of them were
   * deleted.
   */
  breakWeeks: readonly string[];
}

