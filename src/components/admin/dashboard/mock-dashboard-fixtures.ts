function buildProductAttention(
  byId: ReadonlyMap<string, ProductSpec>,
): ProductAttention[] {
  return PRODUCT_ISSUE_SPECS.map(({ productId, issues }) => {
    const spec = byId.get(productId);
    if (spec === undefined) {
      // A queue naming a product the catalogue does not hold would render a card
      // pointing nowhere, which is exactly the drift a fixture is supposed to
      // make impossible. Fail at build time instead.
      throw new Error(`Fixture references unknown product: ${productId}`);
    }
    return {
      productId: spec.id,
      name: spec.name,
      productType: spec.productType,
      href: ROUTES.admin.product(spec.productType, spec.id),
      issues: issues.map(
        (issue, index): ProductIssue => ({
          id: `${spec.id}-${issue.kind}-${index}`,
          ...issue,
        }),
      ),
    };
  });
}

