/**
 * Turn the catalogue into the weeks the schedule steps through.
 *
 * The whole range is resolved up front rather than on demand, because it is
 * eighteen weeks of arithmetic over sixty rows — cheap enough to do once, and
 * doing it once is what lets the body hold nothing but an index.
 */
function resolveWeeks(
  specs: readonly ProductSpec[],
  /** Product ids that appear somewhere in the attention queue. */
  flagged: ReadonlySet<string>,
): { weeks: ScheduleWeek[]; currentWeekIndex: number } {
  const weeks: ScheduleWeek[] = [];
  const firstMonday = addCalendarDays(mondayOf(TODAY), -7 * WEEKS_BEFORE);

  for (let offset = 0; offset <= WEEKS_BEFORE + WEEKS_AFTER; offset += 1) {
    const weekStart = addCalendarDays(firstMonday, 7 * offset);
    const chips: ScheduleChip[] = [];
    const onBreak: string[] = [];

    for (const spec of specs) {
      // A cancelled or completed product is history: it has no occurrences to
      // resolve, whatever its slots still say.
      if (spec.status === "cancelled" || spec.status === "completed") continue;

      const runsThisWeek = spec.slots.some((entry) =>
        withinRun(spec, addCalendarDays(weekStart, entry.weekday)),
      );
      if (!runsThisWeek) continue;

      if (spec.breakWeeks.includes(weekStart)) {
        onBreak.push(spec.name);
        continue;
      }

      for (const entry of spec.slots) {
        const date = addCalendarDays(weekStart, entry.weekday);
        if (!withinRun(spec, date)) continue;
        chips.push({
          id: `${spec.id}-${date}-${entry.startTime}`,
          productId: spec.id,
          productName: spec.name,
          productType: spec.productType,
          weekday: entry.weekday,
          startTime: entry.startTime,
          durationMinutes: entry.durationMinutes,
          activeCount: spec.activeCount,
          seatCount: spec.seatCount,
          needsAttention: flagged.has(spec.id),
          href: ROUTES.admin.product(spec.productType, spec.id),
        });
      }
    }

    weeks.push({ weekStart, chips, onBreak });
  }

  return { weeks, currentWeekIndex: WEEKS_BEFORE };
}

function withinRun(spec: ProductSpec, date: string): boolean {
  if (date < spec.startDate) return false;
  return spec.endDate === null || date <= spec.endDate;
}

/** Every weekday (0…6) a run covers, for a span of at most one week. */
function weekdaysBetween(start: string, end: string): number[] {
  const weekdays: number[] = [];
  let cursor = start;
  while (cursor <= end) {
    weekdays.push(weekdayOf(cursor));
    cursor = addCalendarDays(cursor, 1);
  }
  return weekdays;
}

/**
 * Build the coming-up feed: one entry per milestone, grouped by date and then by
 * kind and product type.
 *
 * A single-date product gets its own kind rather than being called a "start".
 * An event that begins and ends on one evening does not *start* — it happens —
 * and a feed that says "LAN-ilta Kaapelitehdas starts" and then never mentions
 * it again is describing something other than what an event is.
 */
function buildComingUp(specs: readonly ProductSpec[]): ComingUpDay[] {
  const horizonEnd = monthsAfter(`${TODAY.slice(0, 7)}-01`, COMING_UP_MONTHS);
  const inHorizon = (date: string) => date >= TODAY && date < horizonEnd;

  const byDate = new Map<string, Map<string, ComingUpCohort>>();

  const add = (
    date: string,
    kind: ComingUpCohort["kind"],
    spec: ProductSpec,
  ) => {
    const cohortKey = `${kind}-${spec.productType}`;
    let day = byDate.get(date);
    if (day === undefined) {
      day = new Map<string, ComingUpCohort>();
      byDate.set(date, day);
    }
    const existing = day.get(cohortKey);
    const item: ComingUpItem = {
      id: spec.id,
      name: spec.name,
      href: ROUTES.admin.product(spec.productType, spec.id),
      activeCount: spec.activeCount,
      seatCount: spec.seatCount,
    };
    if (existing === undefined) {
      day.set(cohortKey, {
        id: `${date}-${cohortKey}`,
        kind,
        productType: spec.productType,
        items: [item],
      });
    } else {
      day.set(cohortKey, { ...existing, items: [...existing.items, item] });
    }
  };

  for (const spec of specs) {
    if (spec.status === "cancelled" || spec.status === "completed") continue;

    if (spec.endDate === spec.startDate) {
      if (inHorizon(spec.startDate)) add(spec.startDate, "runs", spec);
      continue;
    }
    if (inHorizon(spec.startDate)) add(spec.startDate, "starts", spec);
    if (spec.endDate !== null && inHorizon(spec.endDate)) {
      add(spec.endDate, "ends", spec);
    }
  }

  return [...byDate.entries()]
    .sort(([a], [b]) => (a < b ? -1 : 1))
    .map(([date, cohorts]) => ({
      date,
      cohorts: [...cohorts.values()].sort(compareComingUpCohorts),
    }));
}

