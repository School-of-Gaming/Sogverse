export function buildAdminDashboardFixture(
  scenario: AdminDashboardScenario,
  /**
   * The previewer's locale. Nothing in the catalogue is translated — product
   * names are what they are — but the two `Intl`-formatted values on the page
   * (a gedu's wait here, weekday and month names at the point of render) follow
   * the reader, and a fixture that pinned them to English would make the scene
   * a false picture of the page for four of the five locales.
   */
  locale: SupportedLocale,
): AdminDashboardData {
  const quiet = scenario === "quiet";

  const specs = quiet
    ? quietCatalogue()
    : [...consumerClubs(), ...municipalityClubs(), ...camps(), ...events()];

  const byId = new Map(specs.map((spec) => [spec.id, spec]));
  const products = quiet ? [] : buildProductAttention(byId);

  // The dot on a schedule chip and the cards in the queue are the same fact, so
  // the set of flagged products is taken from the queue rather than listed twice.
  const flagged = new Set(products.map((product) => product.productId));

  const { weeks, currentWeekIndex } = resolveWeeks(specs, flagged);

  return {
    now: ADMIN_DASHBOARD_NOW,
    timeZone: ADMIN_DASHBOARD_TIMEZONE,
    // The whole fixture is authored in the zone it is read in — every product
    // is Helsinki and so is the pinned clock — so nothing converted and there is
    // no adjustment to disclose. The live page decides this per snapshot.
    timeZoneAbbrev: null,
    products,
    // Both scenarios list gedus: certification is no longer part of the
    // attention queue, so an empty queue says nothing about who is waiting on a
    // decision. `quiet` takes the two oldest, which is the pair that shows a
    // clear panel above a list an admin cannot clear today.
    uncertifiedGedus: quiet
      ? uncertifiedGedus(locale).slice(-QUIET_GEDU_COUNT)
      : uncertifiedGedus(locale),
    users: quiet ? QUIET_USER_STATS : BUSY_USER_STATS,
    weeks,
    currentWeekIndex,
    comingUp: buildComingUp(specs),
  };
}

