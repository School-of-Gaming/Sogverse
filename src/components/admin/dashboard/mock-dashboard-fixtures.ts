/**
 * Weekday rotations, weighted towards the middle of the week.
 *
 * Real weeks are not flat — Tuesday to Thursday is when families can get a child
 * to a club, and rows built on an even spread would hide the one thing stacking
 * seven of them is for. The rotation is a literal list rather than a modulus so
 * the weighting is visible at a glance and reproducible exactly.
 */
const PRIMARY_WEEKDAYS = [1, 2, 3, 0, 2, 1, 3, 4, 2, 1, 3, 2, 0, 3, 1, 2, 4, 1, 3, 2];

/** The second weekday of a twice-weekly club — never the same as the first. */
function secondWeekday(primary: number): number {
  return (primary + 2) % 5;
}

