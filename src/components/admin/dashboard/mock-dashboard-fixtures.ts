function consumerClubs(): ProductSpec[] {
  return CONSUMER_CLUB_NAMES.map((name, index) => {
    const id = `consumer-club-${index + 1}`;
    const pendingStart = PENDING_CONSUMER[index];
    const seatCount = CONSUMER_SEATS[index % CONSUMER_SEATS.length];
    const primary = PRIMARY_WEEKDAYS[index % PRIMARY_WEEKDAYS.length];
    // Two clubs run at the weekend, which is the only way the Saturday and
    // Sunday rows ever carry anything — and seven rows whose last two are always
    // empty are five rows with a design flaw.
    const weekendWeekday = index === 22 ? 5 : index === 24 ? 6 : null;

    // Most consumer clubs meet twice a week; a fifth of them once. The mix is
    // what gives the week its density — a hundred-odd resolved sessions across
    // sixty products, peaking around twenty on a Wednesday, which is the load
    // the wrapping row has to stay legible under.
    const slots =
      weekendWeekday === null
        ? [
            slot(primary, index),
            ...(index % 5 === 4 ? [] : [slot(secondWeekday(primary), index + 3)]),
          ]
        : [slot(weekendWeekday, index), slot(primary, index + 1)];

    return {
      id,
      name,
      productType: "consumer_club",
      status: pendingStart === undefined ? "running" : "pending",
      startDate: pendingStart ?? TERM_START,
      // Most consumer clubs are open-ended subscriptions with no last day, so
      // they never appear on the coming-up feed's "ends" side at all.
      endDate: index % 4 === 1 ? CONSUMER_TERM_END : null,
      seatCount,
      activeCount: Math.min(
        CONSUMER_ACTIVE[index % CONSUMER_ACTIVE.length],
        seatCount,
      ),
      slots,
      breakWeeks: [],
    };
  });
}

function municipalityClubs(): ProductSpec[] {
  return MUNICIPALITY_CLUB_NAMES.map((name, index) => {
    const id = `municipality-club-${index + 1}`;
    const waveTwo = index >= MUNICIPALITY_WAVE_TWO_FROM;
    const seatCount = MUNICIPALITY_SEATS[index % MUNICIPALITY_SEATS.length];
    const primary = PRIMARY_WEEKDAYS[(index + 6) % PRIMARY_WEEKDAYS.length];

    return {
      id,
      name,
      productType: "municipality_club",
      status: waveTwo ? "pending" : "running",
      startDate: waveTwo ? MUNICIPALITY_WAVE_TWO_START : TERM_START,
      endDate: MUNICIPALITY_TERM_END,
      seatCount,
      activeCount: Math.min(
        MUNICIPALITY_ACTIVE[index % MUNICIPALITY_ACTIVE.length],
        seatCount,
      ),
      slots:
        index % 3 === 0
          ? [slot(primary, index), slot(secondWeekday(primary), index + 2)]
          : [slot(primary, index)],
      // Four of them carry the holiday break, which is enough to prove the
      // resolved week drops them and enough for the break line under it to stay
      // one readable sentence.
      breakWeeks: index < 4 ? [AUTUMN_BREAK_WEEK] : [],
    };
  });
}

