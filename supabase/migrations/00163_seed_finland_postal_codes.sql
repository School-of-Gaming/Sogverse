-- Fail the migration if the seed did not land whole.
--
-- The generator's gates ran against the source files; these restate them
-- against the database, because this file can be applied by hand long after
-- that run. Counts are exact rather than "at least": a surplus means rows exist
-- this seed does not explain, and that wants a human.
DO $$
DECLARE
  n_rows      bigint;
  n_codes     bigint;
  n_munis     bigint;
  n_uncovered bigint;
BEGIN
  SELECT count(*) INTO n_rows
    FROM public.postal_codes
   WHERE country_code = 'FI';

  IF n_rows <> 3596 THEN
    RAISE EXCEPTION
      'Finland postal seed: expected 3596 rows for FI, found %. A shortfall means the municipality join lost rows the generator matched; a surplus means rows exist this seed does not explain.',
      n_rows;
  END IF;

  SELECT count(DISTINCT postal_code) INTO n_codes
    FROM public.postal_codes
   WHERE country_code = 'FI';

  IF n_codes <> 3596 THEN
    RAISE EXCEPTION 'Finland postal seed: expected 3596 distinct FI postal codes, found %', n_codes;
  END IF;

  -- Coverage, scoped to SOURCED municipalities. `geonames_id IS NOT NULL` is
  -- load-bearing, not decoration: the DB test fixtures in supabase/seed.sql
  -- include a small code-less Finnish tree that no postal source has ever heard
  -- of, and an unscoped count would fail this migration on a database that had
  -- loaded them.
  SELECT count(*) INTO n_munis
    FROM public.locations
   WHERE country_code = 'FI' AND type = 'municipality' AND geonames_id IS NOT NULL;

  IF n_munis <> 308 THEN
    RAISE EXCEPTION
      'Finland postal seed: expected 308 sourced FI municipalities to attach codes to, found %',
      n_munis;
  END IF;

  SELECT count(*) INTO n_uncovered
    FROM public.locations l
   WHERE l.country_code = 'FI' AND l.type = 'municipality' AND l.geonames_id IS NOT NULL
     AND NOT EXISTS (
       SELECT 1 FROM public.postal_codes p WHERE p.location_id = l.id
     );

  IF n_uncovered <> 0 THEN
    RAISE EXCEPTION
      'Finland postal seed: % sourced FI municipalities carry no postal code, expected exactly 0',
      n_uncovered;
  END IF;
END;
$$;

